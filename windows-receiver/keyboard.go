package main

// USB Keyboard/Keypad usages -> PC set-1 scan codes. 0xE0xx denotes an
// extended key; HID usages are never passed through as Windows virtual keys.
func keyScanCode(usage int) (uint16, bool) {
	letters := [...]uint16{0x1e, 0x30, 0x2e, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32, 0x31, 0x18, 0x19, 0x10, 0x13, 0x1f, 0x14, 0x16, 0x2f, 0x11, 0x2d, 0x15, 0x2c}
	if usage >= 4 && usage <= 29 {
		return letters[usage-4], true
	}
	if usage >= 30 && usage <= 39 {
		return uint16(usage - 30 + 2), true
	}
	if usage >= 58 && usage <= 67 {
		return uint16(usage - 58 + 0x3b), true
	}
	code, ok := map[int]uint16{
		40: 0x1c, 41: 0x01, 42: 0x0e, 43: 0x0f, 44: 0x39, 45: 0x0c, 46: 0x0d, 47: 0x1a, 48: 0x1b,
		49: 0x2b, 51: 0x27, 52: 0x28, 53: 0x29, 54: 0x33, 55: 0x34, 56: 0x35, 57: 0x3a,
		68: 0x57, 69: 0x58, 73: 0xe052, 74: 0xe047, 75: 0xe049, 76: 0xe053, 77: 0xe04f, 78: 0xe051,
		79: 0xe04d, 80: 0xe04b, 81: 0xe050, 82: 0xe048,
		224: 0x1d, 225: 0x2a, 226: 0x38, 227: 0xe05b, 228: 0xe01d, 229: 0x36, 230: 0xe038, 231: 0xe05c,
	}[usage]
	return code, ok
}
